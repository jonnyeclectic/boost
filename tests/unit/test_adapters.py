class TestModelOmittedIsUnchanged:
    """model=None (the opt-out) must reproduce the original framework-default
    output byte-for-byte — no LLM import, no llm/model kwarg."""

    def test_crewai_no_llm_when_model_none(self):
        src = adapters.render_crewai("x", "d", "b", None)
        assert "LLM" not in src
        assert "llm=" not in src
        assert src == adapters.render_crewai("x", "d", "b")

    def test_agents_sdk_no_model_when_none(self):
        src = adapters.render_agents_sdk("x", "d", "b", None)
        assert "LitellmModel" not in src
        assert "model=" not in src
        assert src == adapters.render_agents_sdk("x", "d", "b")

    def test_empty_model_is_treated_as_omitted(self):
        # falsy model ("") must not emit an LLM line
        assert "LLM" not in adapters.render_crewai("x", "d", "b", "")

    @pytest.mark.parametrize("fmt", ["crewai", "agents-sdk", "langgraph"])
    def test_render_dispatch_passes_model_through(self, fmt):
        src = adapters.render(fmt, "x", "d", "b", "claude-x")
        # crewai/agents-sdk emit litellm anthropic/claude-x; langgraph emits the
        # LangChain anthropic:claude-x — either way the model is wired through.
        assert "claude-x" in src and "anthropic" in src
        compile(src, "<c>", "exec")

    @pytest.mark.parametrize("fmt", ["crewai", "agents-sdk", "langgraph"])
    def test_model_output_still_compiles(self, fmt):
        compile(adapters.render(fmt, "s", "d", 'body """ x', "claude-y"),
                "<c>", "exec")
