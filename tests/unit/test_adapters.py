class TestAdversarialBodiesStayValid:
    """A skill body full of quote/escape hazards must still emit valid Python."""

    HAZARDS: ClassVar[list] = [
        'has "double" and \'single\' quotes',
        'triple """ quotes """ inside',
        "trailing backslash \\",
        "newlines\nand\ttabs",
        "unicode → café 🚀 ↯",
        "",
    ]

    @pytest.mark.parametrize("body", HAZARDS)
    def test_crewai_compiles(self, body):
        compile(adapters.render_crewai("s", "d", body), "<c>", "exec")

    @pytest.mark.parametrize("body", HAZARDS)
    def test_agents_sdk_compiles(self, body):
        compile(adapters.render_agents_sdk("s", "d", body), "<c>", "exec")

    @pytest.mark.parametrize("body", HAZARDS)
    def test_langgraph_compiles(self, body):
        compile(adapters.render_langgraph("s", "d", body), "<c>", "exec")

    def test_body_round_trips_through_the_literal(self):
        # Extract the backstory literal and confirm it decodes to the original.
        body = 'weird """ body with "quotes" and \\ slashes\nand lines'
        src = adapters.render_crewai("s", "d", body)
        tree = ast.parse(src)
        call = tree.body[-1].value  # the Agent(...) call
        backstory = next(k.value for k in call.keywords if k.arg == "backstory")
        assert ast.literal_eval(backstory) == body


